-- 3. Create Services Table
CREATE TABLE IF NOT EXISTS public.services (
  id              bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  en              text NOT NULL,
  ar              text NOT NULL,
  img             text,
  cat             text,
  unit            text,
  price           numeric NOT NULL DEFAULT 0,
  duration        text,
  description_en  text,
  description_ar  text,
  is_shared       boolean NOT NULL DEFAULT false,
  enable_reminder boolean NOT NULL DEFAULT true,
  branch_pricing  jsonb NOT NULL DEFAULT '{}'::jsonb,
  sort_order      integer NOT NULL DEFAULT 0,
  visible         boolean NOT NULL DEFAULT true,
  active          boolean NOT NULL DEFAULT true,
  created_at      timestamptz DEFAULT now()
);

-- 4. Create Providers Table
CREATE TABLE IF NOT EXISTS public.providers (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name                text NOT NULL,
  bookings_count      integer NOT NULL DEFAULT 0,
  services            jsonb NOT NULL DEFAULT '[]'::jsonb,
  more_count          integer NOT NULL DEFAULT 0,
  rating              numeric NOT NULL DEFAULT 0,
  image               text,
  phone               text,
  gender              text,
  age                 integer,
  specialty           text,
  national_id         text,
  working_days_hours  jsonb,
  branch_id           uuid REFERENCES public.branches(id) ON DELETE SET NULL,
  start_date          date,
  created_at          timestamptz DEFAULT now()
);

-- 5. Create Provider Attendance Table
CREATE TABLE IF NOT EXISTS public.provider_attendance (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  provider_id  uuid REFERENCES public.providers(id) ON DELETE CASCADE,
  date         date NOT NULL,
  status       text NOT NULL CHECK (status IN ('Present', 'Absent', 'On Leave')),
  check_in     time,
  check_out    time,
  notes        text,
  created_at   timestamptz DEFAULT now(),
  updated_at   timestamptz DEFAULT now(),
  UNIQUE(provider_id, date)
);

-- 6. Create Customers Table
CREATE TABLE IF NOT EXISTS public.customers (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name                text NOT NULL,
  mobile              text NOT NULL UNIQUE,
  gender              text,
  email               text,
  number_of_bookings  integer DEFAULT 0,
  registration_date   timestamptz DEFAULT now(),
  active              boolean DEFAULT true,
  spent_amount        numeric DEFAULT 0,
  outstanding         numeric DEFAULT 0,
  area                text,
  location_name       text,
  street_name         text,
  building_no         text,
  floor_no            text,
  note                text,
  age                 integer,
  national_id         text,
  address             text,
  referral            text,
  occupation          text,
  created_at          timestamptz DEFAULT now(),
  updated_at          timestamptz DEFAULT now()
);

-- 7. Create Reservations Table
CREATE TABLE IF NOT EXISTS public.reservations (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  service_id      bigint,
  date            text NOT NULL,
  requested_time  text NOT NULL,
  name            text,
  email           text,
  phone           text,
  notes           text,
  status          text NOT NULL DEFAULT 'pending',
  time_slot       text,
  session_type    text,
  doctor_name     text,
  amount_paid     numeric DEFAULT 0,
  amount_left     numeric DEFAULT 0,
  branch_id       uuid REFERENCES public.branches(id) ON DELETE SET NULL,
  customer_id     uuid REFERENCES public.customers(id) ON DELETE SET NULL,
  created_at      timestamptz DEFAULT now(),
  updated_at      timestamptz DEFAULT now()
);

-- 8. Create Page Settings Table
CREATE TABLE IF NOT EXISTS public.page_settings (
  key         text PRIMARY KEY,
  value       jsonb NOT NULL,
  created_at  timestamptz DEFAULT now(),
  updated_at  timestamptz DEFAULT now()
);

-- 9. Create Admin Roles Table
CREATE TABLE IF NOT EXISTS public.roles (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name        text UNIQUE NOT NULL,
  permissions text[] NOT NULL,
  created_at  timestamptz DEFAULT now(),
  updated_at  timestamptz DEFAULT now()
);

-- 10. Create Employee Accounts Table
CREATE TABLE IF NOT EXISTS public.employee_accounts (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  auth_user_id   uuid UNIQUE,
  employee_id    text UNIQUE NOT NULL,
  role_name      text REFERENCES public.roles(name) ON UPDATE CASCADE ON DELETE SET NULL,
  email          text UNIQUE NOT NULL,
  created_at     timestamptz DEFAULT now()
);

