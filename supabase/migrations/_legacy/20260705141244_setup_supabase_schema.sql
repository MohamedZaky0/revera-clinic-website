-- Disable Row Level Security (RLS) on public client tables to allow easy client access
ALTER TABLE public.branches DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.services DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.providers DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.provider_attendance DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.customers DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.reservations DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.page_settings DISABLE ROW LEVEL SECURITY;

-- Enable RLS for Roles and Employee Accounts (Authenticated server access only)
ALTER TABLE public.roles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.employee_accounts ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read access to roles" ON public.roles FOR SELECT USING (true);
CREATE POLICY "Allow service_role full access to roles" ON public.roles FOR ALL TO service_role USING (true);

CREATE POLICY "Allow public read access to employee_accounts" ON public.employee_accounts FOR SELECT USING (true);
CREATE POLICY "Allow service_role full access to employee_accounts" ON public.employee_accounts FOR ALL TO service_role USING (true);
